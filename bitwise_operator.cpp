#include<bits/stdc++.h>
using namespace std;
int main()
{
	int a,b;
	cin>>a>>b;

	cout<<" a&b is "<<(a&b)<<endl;
	cout<<" a|b is "<<(a|b)<<endl;
	cout<<" ~a is "<<(~a)<<endl;
	cout<<" a^b is "<<(a^b)<<endl;
	cout<<" a>>b is "<<(a>>b)<<endl;
	cout<<"(left shift) a<<b is "<<(a<<b)<<endl;

	cout<<(19<<2)<<endl;
	cout<<(21>>2)<<endl;

}